export function getTimeZoneOffset(timeZone) {
	let offMin = 0;

	if (timeZone !== '+00:00') {
		const mOff = timeZone.match(/^([+-])(\d{2}):?(\d{2})$/);
		if (!mOff) throw new Error('Bad offset');
		const sign = mOff[1] === '+' ? 1 : -1;
		const oh = +mOff[2], om = +mOff[3];
		offMin = sign * (oh * 60 + om);
	}

	return offMin * 60 * 1000;
}